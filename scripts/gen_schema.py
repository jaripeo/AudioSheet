def py_literal(value: str | float) -> str:
    """Render a literal value as Python source."""
    return json.dumps(value) if isinstance(value, str) else repr(value)


def py_type(node: TypeNode, annotations: Annotations, schema: Schema) -> str:
    """Render a type node as a Python type expression.

    Args:
        node: The type to render.
        annotations: Annotations that propagate into numeric primitives.
        schema: The symbol table.

    Returns:
        A Python type expression as source text.
    """
    if isinstance(node, TPrimitive):
        if node.name == "number":
            base = "int" if annotations.integer else "float"
            return _annotated(base, annotations)
        return "str" if node.name == "string" else "bool"

    if isinstance(node, TNull):
        return "None"

    if isinstance(node, TLiteral):
        return f"Literal[{py_literal(node.value)}]"

    if isinstance(node, TRef):
        if annotations.has_bounds and _is_numeric_alias(node.name, schema):
            return _annotated(node.name, annotations)
        return node.name

    if isinstance(node, TArray):
        return f"list[{py_type(node.item, annotations, schema)}]"

    if isinstance(node, TTuple):
        inner = ", ".join(py_type(item, annotations, schema) for item in node.items)
        return f"tuple[{inner}]"

    if isinstance(node, TUnion):
        literals = [m for m in node.members if isinstance(m, TLiteral)]
        has_null = any(isinstance(m, TNull) for m in node.members)
        others = [m for m in node.members if not isinstance(m, TLiteral | TNull)]
        parts: list[str] = []
        if literals:
            values = ", ".join(py_literal(m.value) for m in literals)
            parts.append(f"Literal[{values}]")
        parts.extend(py_type(member, annotations, schema) for member in others)
        if has_null:
            parts.append("None")
        return " | ".join(parts)

    raise ParseError(f"cannot render {node!r} as a Python type")


def _annotated(base: str, annotations: Annotations) -> str:
    if not annotations.has_bounds:
        return base
    constraints: list[str] = []
    if annotations.minimum is not None:
        constraints.append(f"ge={_number(annotations.minimum)}")
    if annotations.maximum is not None:
        constraints.append(f"le={_number(annotations.maximum)}")
    return f"Annotated[{base}, Field({', '.join(constraints)})]"


def _docstring(text: str | None, indent: str, fallback: str) -> list[str]:
    body = text or fallback
    wrapped = body if body.endswith(".") else f"{body}."
    if len(indent) + len(wrapped) + 6 <= 96:
        return [f'{indent}"""{wrapped}"""']
    words = wrapped.split()
    lines: list[str] = []
    current = indent
    for word in words:
        candidate = f"{current} {word}" if current.strip() else f"{indent}{word}"
        if len(candidate) > 92 and current.strip():
            lines.append(current)
            current = f"{indent}{word}"
        else:
            current = candidate
    lines.append(current)
    return [f'{indent}"""', *lines, f'{indent}"""']


def build_pydantic_module(
    schema: Schema, names: list[str], source_fingerprint: str
) -> str:
    """Render the single generated Pydantic module holding every model."""
    lines: list[str] = [
        '"""ScoreDocument contract as Pydantic v2 models.',
        "",
        f"{GENERATED_BANNER}",
        "",
        "Source of truth: packages/schema/src/*.ts (ARCHITECTURE.md Section 3).",
        "Every model forbids unknown keys: an unexpected field means a version",
        "mismatch and MUST fail (Section 3.7).",
        "",
        f"Source fingerprint: {source_fingerprint}",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Annotated, Literal",
        "",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
        "__all__ = [",
    ]
    lines.extend(f'    "{name}",' for name in sorted(names))
    lines.extend(["]", ""])

    for name in names:
        declaration = schema.resolve(name)
        lines.append("")
        if isinstance(declaration, Alias):
            rendered = py_type(declaration.type, declaration.annotations, schema)
            if declaration.annotations.description:
                lines.append(f"#: {declaration.annotations.description}")
            lines.append(f"{name} = {rendered}")
            lines.append("")
        else:
            lines.append(f"class {name}(BaseModel):")
            lines.extend(
                _docstring(
                    declaration.annotations.description,
                    "    ",
                    f"{name} contract model",
                )
            )
            lines.append("")
            lines.append('    model_config = ConfigDict(extra="forbid")')
            lines.append("")
            for member in declaration.fields:
                rendered = py_type(member.type, member.annotations, schema)
                if member.optional:
                    lines.append(f"    {member.name}: {rendered} = None")
                else:
                    lines.append(f"    {member.name}: {rendered}")
            lines.append("")

    return "\n".join(lines).rstrip("\n") + "\n"


def build_reexport_module(
    module_name: str, ts_module: str, schema: Schema, names: list[str]
) -> str:
    """Render a thin module re-exporting the types declared in one TS module."""
    exported = [n for n in names if schema.resolve(n).module == ts_module]
    lines = [
        f'"""{ts_module} slice of the ScoreDocument contract.',
        "",
        f"{GENERATED_BANNER}",
        "",
        "Every model lives in score_document.py so that the generated package has",
        "no internal import cycles; this module re-exports its slice for callers",
        "that prefer the narrower import.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
    ]
    if exported:
        lines.append("from audiosheet.schema.score_document import (")
        lines.extend(f"    {name}," for name in sorted(exported))
        lines.append(")")
        lines.append("")
        lines.append("__all__ = [")
        lines.extend(f'    "{name}",' for name in sorted(exported))
        lines.append("]")
    else:
        lines.append("__all__: list[str] = []")
    return "\n".join(lines) + "\n"


def build_schema_init(names: list[str]) -> str:
    """Render ``core/audiosheet/schema/__init__.py``."""
    lines = [
        '"""Generated ScoreDocument contract models.',
        "",
        f"{GENERATED_BANNER}",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from audiosheet.schema.score_document import (",
    ]
    lines.extend(f"    {name}," for name in sorted(names))
    lines.extend([")", "", "__all__ = ["])
    lines.extend(f'    "{name}",' for name in sorted(names))
    lines.append("]")
    return "\n".join(lines) + "\n"


