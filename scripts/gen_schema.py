@dataclass(frozen=True)
class Annotations:
    """Generator annotations attached to a type alias or an interface field."""

    description: str | None = None
    integer: bool = False
    minimum: float | None = None
    maximum: float | None = None

    @property
    def has_bounds(self) -> bool:
        """Return whether either bound is set."""
        return self.minimum is not None or self.maximum is not None


@dataclass(frozen=True)
class TPrimitive:
    """``number``, ``string`` or ``boolean``."""

    name: str


@dataclass(frozen=True)
class TNull:
    """The ``null`` type."""


@dataclass(frozen=True)
class TLiteral:
    """A string or numeric literal type."""

    value: str | int | float


@dataclass(frozen=True)
class TRef:
    """A reference to a named type."""

    name: str


@dataclass(frozen=True)
class TArray:
    """``T[]``."""

    item: TypeNode


@dataclass(frozen=True)
class TTuple:
    """``[A, B]``."""

    items: tuple[TypeNode, ...]


@dataclass(frozen=True)
class TUnion:
    """``A | B | null``."""

    members: tuple[TypeNode, ...]


@dataclass(frozen=True)
class TObject:
    """An inline object type."""

    fields: tuple[Field, ...]


TypeNode = TPrimitive | TNull | TLiteral | TRef | TArray | TTuple | TUnion | TObject


@dataclass(frozen=True)
class Field:
    """One interface member."""

    name: str
    type: TypeNode
    annotations: Annotations
    optional: bool = False


@dataclass
class Alias:
    """``export type Name = ...``."""

    name: str
    type: TypeNode
    annotations: Annotations
    module: str


@dataclass
class Interface:
    """``export interface Name { ... }``."""

    name: str
    fields: list[Field]
    annotations: Annotations
    module: str


Declaration = Alias | Interface


# ---------------------------------------------------------------------------
# Doc-comment annotations
# ---------------------------------------------------------------------------

TAG_RE: Final[re.Pattern[str]] = re.compile(
    r"@(integer|minimum|maximum)(?:\s+(-?[\d.]+))?"
)


def parse_doc(raw: str | None) -> Annotations:
    """Parse a doc comment into description text and generator annotations.

    Args:
        raw: The comment body, without the ``/**`` and ``*/`` delimiters.

    Returns:
        The parsed annotations.
    """
    if raw is None:
        return Annotations()

    lines = [re.sub(r"^\s*\*\s?", "", line) for line in raw.splitlines()]
    body = "\n".join(lines).strip()

    integer = False
    minimum: float | None = None
    maximum: float | None = None
    for match in TAG_RE.finditer(body):
        tag, value = match.group(1), match.group(2)
        if tag == "integer":
            integer = True
        elif tag == "minimum" and value is not None:
            minimum = float(value)
        elif tag == "maximum" and value is not None:
            maximum = float(value)

    stripped = re.sub(r"\s+", " ", TAG_RE.sub("", body)).strip()
    description: str | None = stripped or None
    return Annotations(
        description=description, integer=integer, minimum=minimum, maximum=maximum
    )


