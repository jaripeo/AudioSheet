@dataclass
class Schema:
    """Every declaration parsed from the TypeScript source."""

    declarations: dict[str, Declaration] = field(default_factory=dict)
    order: list[str] = field(default_factory=list)
    module_docs: dict[str, str] = field(default_factory=dict)

    def add(self, declaration: Declaration) -> None:
        """Register a declaration, rejecting duplicates.

        Raises:
            ParseError: When two modules declare the same name.
        """
        if declaration.name in self.declarations:
            existing = self.declarations[declaration.name]
            raise ParseError(
                f"duplicate declaration {declaration.name!r} in "
                f"{declaration.module} and {existing.module}"
            )
        self.declarations[declaration.name] = declaration
        self.order.append(declaration.name)

    def resolve(self, name: str) -> Declaration:
        """Look up a declaration by name, following indexed access.

        Raises:
            ParseError: When the name or the accessed field is unknown.
        """
        if '["' in name:
            owner, _, rest = name.partition('["')
            key = rest.rstrip('"]')
            declaration = self.resolve(owner)
            if not isinstance(declaration, Interface):
                raise ParseError(f"indexed access on non-interface {owner!r}")
            for member in declaration.fields:
                if member.name == key:
                    return Alias(
                        name=name,
                        type=member.type,
                        annotations=member.annotations,
                        module=declaration.module,
                    )
            raise ParseError(f"{owner!r} has no field {key!r}")
        if name not in self.declarations:
            raise ParseError(f"unknown type {name!r}")
        return self.declarations[name]


def parse_all(src_dir: Path) -> Schema:
    """Parse every TypeScript module listed in ``TS_MODULES``.

    Args:
        src_dir: ``packages/schema/src``.

    Returns:
        The populated symbol table.

    Raises:
        SystemExit: When a declared module is missing.
    """
    schema = Schema()
    for module in TS_MODULES:
        path = src_dir / module
        if not path.is_file():
            raise SystemExit(f"missing TypeScript module: {path}")
        tokens = lex(path.read_text(encoding="utf-8"), module)
        declarations, module_doc = Parser(tokens, module).parse_module()
        if module_doc is not None:
            schema.module_docs[module] = module_doc
        for declaration in declarations:
            schema.add(declaration)
    return schema


def referenced_names(node: TypeNode) -> set[str]:
    """Return every named type referenced anywhere inside ``node``."""
    if isinstance(node, TRef):
        return {node.name}
    if isinstance(node, TArray):
        return referenced_names(node.item)
    if isinstance(node, TTuple):
        return set().union(*(referenced_names(item) for item in node.items))
    if isinstance(node, TUnion):
        return set().union(*(referenced_names(member) for member in node.members))
    if isinstance(node, TObject):
        return (
            set().union(*(referenced_names(f.type) for f in node.fields))
            if node.fields
            else set()
        )
    return set()


def reachable(schema: Schema, roots: tuple[str, ...]) -> list[str]:
    """Return the reachable declaration names in dependency-first order.

    Args:
        schema: The parsed symbol table.
        roots: Names to start from.

    Returns:
        Names ordered so that every type appears after everything it references.

    Raises:
        ParseError: When the type graph contains a cycle.
    """
    ordered: list[str] = []
    state: dict[str, str] = {}

    def visit(name: str) -> None:
        mark = state.get(name)
        if mark == "done":
            return
        if mark == "active":
            raise ParseError(f"cyclic type reference through {name!r}")
        state[name] = "active"
        declaration = schema.resolve(name)
        node = declaration.type if isinstance(declaration, Alias) else None
        deps = referenced_names(node) if node is not None else set()
        if isinstance(declaration, Interface):
            deps = set().union(*(referenced_names(f.type) for f in declaration.fields))
        for dep in sorted(deps):
            visit(dep)
        state[name] = "done"
        ordered.append(name)

    for root in roots:
        visit(root)
    return ordered


