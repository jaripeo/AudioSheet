# ---------------------------------------------------------------------------
# Lexer
# ---------------------------------------------------------------------------

TOKEN_PUNCT: Final[str] = "{}[]()<>|&;:,=?."
IDENT_RE: Final[re.Pattern[str]] = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")
NUMBER_RE: Final[re.Pattern[str]] = re.compile(r"-?\d+(?:\.\d+)?")


@dataclass(frozen=True)
class Token:
    """A lexical token. ``kind`` is one of doc/ident/string/number/punct/eof."""

    kind: str
    value: str
    line: int


class LexError(RuntimeError):
    """The TypeScript source left the supported subset while lexing."""


def lex(source: str, origin: str) -> list[Token]:
    """Tokenise TypeScript source, keeping ``/** ... */`` comments as doc tokens.

    Args:
        source: File contents.
        origin: File name, used in error messages.

    Returns:
        The token list, terminated by an ``eof`` token.

    Raises:
        LexError: On an unterminated string or comment.
    """
    tokens: list[Token] = []
    i = 0
    line = 1
    n = len(source)

    while i < n:
        ch = source[i]

        if ch == "\n":
            line += 1
            i += 1
            continue
        if ch in " \t\r":
            i += 1
            continue

        if source.startswith("/**", i):
            end = source.find("*/", i + 3)
            if end == -1:
                raise LexError(f"{origin}:{line}: unterminated doc comment")
            tokens.append(Token("doc", source[i + 3 : end], line))
            line += source.count("\n", i, end)
            i = end + 2
            continue

        if source.startswith("/*", i):
            end = source.find("*/", i + 2)
            if end == -1:
                raise LexError(f"{origin}:{line}: unterminated block comment")
            line += source.count("\n", i, end)
            i = end + 2
            continue

        if source.startswith("//", i):
            end = source.find("\n", i)
            i = n if end == -1 else end
            continue

        if ch in "\"'`":
            end = i + 1
            while end < n and source[end] != ch:
                if source[end] == "\\":
                    end += 1
                end += 1
            if end >= n:
                raise LexError(f"{origin}:{line}: unterminated string")
            tokens.append(Token("string", source[i + 1 : end], line))
            line += source.count("\n", i, end)
            i = end + 1
            continue

        number = NUMBER_RE.match(source, i)
        if number is not None and (
            ch.isdigit() or (ch == "-" and _next_is_digit(source, i))
        ):
            tokens.append(Token("number", number.group(0), line))
            i = number.end()
            continue

        ident = IDENT_RE.match(source, i)
        if ident is not None:
            tokens.append(Token("ident", ident.group(0), line))
            i = ident.end()
            continue

        if ch in TOKEN_PUNCT:
            tokens.append(Token("punct", ch, line))
            i += 1
            continue

        # Operators and syntax that only occur in value-level code, which the
        # parser skips wholesale.
        tokens.append(Token("punct", ch, line))
        i += 1

    tokens.append(Token("eof", "", line))
    return tokens


def _next_is_digit(source: str, index: int) -> bool:
    return index + 1 < len(source) and source[index + 1].isdigit()


