#!/usr/bin/env python3
"""Generate the JSON Schema and the Pydantic models from the TypeScript schema.

ARCHITECTURE.md Section 3 makes ``packages/schema/src/*.ts`` the single source of
truth for every inter-stage contract, and requires both downstream artefacts to
be generated:

* ``packages/schema/schema/score-document.schema.json`` — the only validator used
  at the S6 gate (Section 3.7).
* ``core/audiosheet/schema/*.py`` — Pydantic v2 models used by the Python core.

Neither artefact may be hand-edited. Run ``make schema`` to regenerate and
``make schema-check`` to fail a build on drift.

The TypeScript is written in a deliberately small, declarative subset: type
aliases, interfaces, literal unions, arrays, tuples, parenthesised types and
nullable unions. That subset is parsed here directly, so the generator has no
Node.js dependency (see docs/adr/0004-python-schema-generator.md).

Generator annotations, written in a ``/** ... */`` comment above a type alias or
an interface field:

    @integer        the value is integral (JSON "integer", Python ``int``)
    @minimum <n>    inclusive lower bound
    @maximum <n>    inclusive upper bound

Numeric annotations propagate through arrays, tuples and nullable unions down to
the ``number`` primitives they contain.
"""

