def source_fingerprint(src_dir: Path) -> str:
    """Return a stable BLAKE3-or-SHA256 fingerprint of the TypeScript sources."""
    payload = b""
    for module in TS_MODULES:
        payload += module.encode("utf-8")
        payload += (src_dir / module).read_bytes()
    try:
        from blake3 import blake3

        return "b3:" + blake3(payload).hexdigest()[:32]
    except ImportError:
        import hashlib

        return "sha256:" + hashlib.sha256(payload).hexdigest()[:32]


def canonical_json(value: object) -> str:
    """Serialise to the project's canonical JSON form (sorted keys, newline)."""
    return (
        json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
        + "\n"
    )


def pretty_json(value: object) -> str:
    """Serialise to stable, human-readable JSON for files humans read."""
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


@dataclass
class Artefact:
    """One generated file and its intended content."""

    path: Path
    content: str


def generate(src_dir: Path) -> list[Artefact]:
    """Parse the TypeScript sources and return every artefact to be written."""
    schema = parse_all(src_dir)
    names = reachable(schema, ROOTS)
    fingerprint = source_fingerprint(src_dir)

    artefacts = [
        Artefact(
            JSON_SCHEMA_OUT, pretty_json(build_json_schema(schema, names, fingerprint))
        ),
        Artefact(
            PY_SCHEMA_DIR / "score_document.py",
            build_pydantic_module(schema, names, fingerprint),
        ),
        Artefact(PY_SCHEMA_DIR / "__init__.py", build_schema_init(names)),
    ]
    for module_name, ts_module in PY_REEXPORTS.items():
        artefacts.append(
            Artefact(
                PY_SCHEMA_DIR / module_name,
                build_reexport_module(module_name, ts_module, schema, names),
            )
        )
    return artefacts


def main(argv: list[str] | None = None) -> int:
    """Entry point.

    Args:
        argv: Command-line arguments; ``sys.argv[1:]`` when ``None``.

    Returns:
        Process exit status: 0 on success, 1 on drift under ``--check``.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the generated files are up to date; write nothing",
    )
    args = parser.parse_args(argv)

    artefacts = generate(TS_SRC_DIR)

    if args.check:
        stale = [
            a.path
            for a in artefacts
            if not a.path.is_file() or a.path.read_text(encoding="utf-8") != a.content
        ]
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
            print("run `make schema` to regenerate", file=sys.stderr)
            return 1
        print(f"schema up to date ({len(artefacts)} artefacts)")
        return 0

    for artefact in artefacts:
        artefact.path.parent.mkdir(parents=True, exist_ok=True)
        artefact.path.write_text(artefact.content, encoding="utf-8")
        print(f"wrote {artefact.path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
