JsonSchema = dict[str, object]


def _bounds(annotations: Annotations) -> JsonSchema:
    out: JsonSchema = {}
    if annotations.minimum is not None:
        out["minimum"] = _number(annotations.minimum)
    if annotations.maximum is not None:
        out["maximum"] = _number(annotations.maximum)
    return out


def _number(value: float) -> int | float:
    """Return ``value`` as an int when it is integral, so JSON stays tidy."""
    return int(value) if float(value).is_integer() else value


def json_type(node: TypeNode, annotations: Annotations, schema: Schema) -> JsonSchema:
    """Render a type node as a JSON Schema fragment.

    Args:
        node: The type to render.
        annotations: Annotations that propagate into numeric primitives.
        schema: The symbol table, used to fold literal unions into enums.

    Returns:
        The JSON Schema fragment.
    """
    if isinstance(node, TPrimitive):
        if node.name == "number":
            out: JsonSchema = {"type": "integer" if annotations.integer else "number"}
            out.update(_bounds(annotations))
            return out
        return {"type": "string" if node.name == "string" else "boolean"}

    if isinstance(node, TNull):
        return {"type": "null"}

    if isinstance(node, TLiteral):
        return {"const": node.value}

    if isinstance(node, TRef):
        out = {"$ref": f"#/$defs/{node.name}"}
        if annotations.has_bounds and _is_numeric_alias(node.name, schema):
            out.update(_bounds(annotations))
        return out

    if isinstance(node, TArray):
        return {"type": "array", "items": json_type(node.item, annotations, schema)}

    if isinstance(node, TTuple):
        return {
            "type": "array",
            "prefixItems": [
                json_type(item, annotations, schema) for item in node.items
            ],
            "items": False,
            "minItems": len(node.items),
            "maxItems": len(node.items),
        }

    if isinstance(node, TObject):
        return json_object([*node.fields], schema, description=None)

    if isinstance(node, TUnion):
        enum_values = _literal_union_values(node)
        if enum_values is not None:
            return {"enum": enum_values}
        return {
            "anyOf": [json_type(member, annotations, schema) for member in node.members]
        }

    raise ParseError(f"cannot render {node!r} as JSON Schema")


def _literal_union_values(node: TUnion) -> list[str | int | float | None] | None:
    """Return a union's literal values, or ``None`` if it is not all literals.

    A union of literals renders as a JSON Schema ``enum``, which is both smaller and
    more readable than an ``anyOf`` of ``const`` fragments.

    Args:
        node: The union to inspect.

    Returns:
        The literal values in declaration order, or ``None``.
    """
    values: list[str | int | float | None] = []
    for member in node.members:
        if isinstance(member, TNull):
            values.append(None)
        elif isinstance(member, TLiteral):
            values.append(member.value)
        else:
            return None
    return values


def _is_numeric_alias(name: str, schema: Schema) -> bool:
    declaration = schema.declarations.get(name)
    return (
        isinstance(declaration, Alias)
        and isinstance(declaration.type, TPrimitive)
        and declaration.type.name == "number"
    )


def json_object(
    fields: list[Field], schema: Schema, *, description: str | None
) -> JsonSchema:
    """Render an object type. Every non-optional field is required.

    ``additionalProperties`` is always ``false``: an unexpected key means a
    version mismatch and MUST fail (ARCHITECTURE.md Section 3.7).
    """
    properties: JsonSchema = {}
    required: list[str] = []
    for member in fields:
        fragment = json_type(member.type, member.annotations, schema)
        if member.annotations.description:
            fragment = {"description": member.annotations.description, **fragment}
        properties[member.name] = fragment
        if not member.optional:
            required.append(member.name)

    out: JsonSchema = {"type": "object"}
    if description:
        out["description"] = description
    out["properties"] = properties
    out["required"] = required
    out["additionalProperties"] = False
    return out


def build_json_schema(
    schema: Schema, names: list[str], source_fingerprint: str
) -> JsonSchema:
    """Assemble the complete score-document JSON Schema document."""
    defs: JsonSchema = {}
    for name in names:
        declaration = schema.resolve(name)
        if isinstance(declaration, Interface):
            defs[name] = json_object(
                declaration.fields,
                schema,
                description=declaration.annotations.description,
            )
        else:
            fragment = json_type(declaration.type, declaration.annotations, schema)
            if declaration.annotations.description:
                fragment = {
                    "description": declaration.annotations.description,
                    **fragment,
                }
            defs[name] = fragment

    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://audiosheet.invalid/schema/score-document.schema.json",
        "title": "ScoreDocument",
        "description": (
            "The only inter-stage contract in AudioSheet (INV-4). Generated from "
            "packages/schema/src/*.ts; do not hand-edit."
        ),
        "x-generated-by": "scripts/gen_schema.py",
        "x-source-fingerprint": source_fingerprint,
        "$ref": "#/$defs/ScoreDocument",
        "$defs": defs,
    }


