class ParseError(RuntimeError):
    """The TypeScript source left the supported subset while parsing."""


class Parser:
    """Recursive-descent parser for the supported TypeScript subset."""

    def __init__(self, tokens: list[Token], module: str) -> None:
        """Create a parser over ``tokens`` originating from ``module``."""
        self.tokens = tokens
        self.module = module
        self.pos = 0

    # -- token helpers --------------------------------------------------

    def peek(self, offset: int = 0) -> Token:
        """Return the token at ``offset`` from the cursor without consuming it."""
        index = min(self.pos + offset, len(self.tokens) - 1)
        return self.tokens[index]

    def next(self) -> Token:
        """Consume and return the token under the cursor."""
        token = self.peek()
        self.pos += 1
        return token

    def at_punct(self, value: str) -> bool:
        """Return whether the cursor is on punctuation ``value``."""
        token = self.peek()
        return token.kind == "punct" and token.value == value

    def at_ident(self, value: str) -> bool:
        """Return whether the cursor is on identifier ``value``."""
        token = self.peek()
        return token.kind == "ident" and token.value == value

    def expect_punct(self, value: str) -> None:
        """Consume punctuation ``value`` or raise.

        Raises:
            ParseError: When the cursor is not on ``value``.
        """
        token = self.next()
        if token.kind != "punct" or token.value != value:
            raise ParseError(
                f"{self.module}:{token.line}: expected {value!r}, got {token.value!r}"
            )

    # -- declarations ---------------------------------------------------

    def parse_module(self) -> tuple[list[Declaration], str | None]:
        """Parse a whole module.

        Returns:
            The declarations found, and the module's header doc comment if any.
        """
        declarations: list[Declaration] = []
        module_doc: str | None = None
        pending_doc: str | None = None

        while self.peek().kind != "eof":
            token = self.peek()

            if token.kind == "doc":
                self.next()
                if module_doc is None and not declarations:
                    module_doc = token.value
                else:
                    pending_doc = token.value
                continue

            if token.kind == "ident" and token.value == "import":
                self._skip_statement()
                continue

            if token.kind == "ident" and token.value == "export":
                nxt = self.peek(1)
                if (
                    nxt.kind == "ident"
                    and nxt.value == "type"
                    and self._is_type_alias()
                ):
                    self.next()
                    declarations.append(self.parse_alias(pending_doc))
                    pending_doc = None
                    continue
                if nxt.kind == "ident" and nxt.value == "interface":
                    self.next()
                    declarations.append(self.parse_interface(pending_doc))
                    pending_doc = None
                    continue
                # export const / function / * from ... — value level, skipped.
                self._skip_statement()
                pending_doc = None
                continue

            # Anything else at top level is value-level code.
            self._skip_statement()
            pending_doc = None

        return declarations, module_doc

    def _is_type_alias(self) -> bool:
        """Distinguish ``export type X =`` from ``export type { ... } from``."""
        return self.peek(2).kind == "ident" and self.peek(3).value == "="

    def parse_alias(self, doc: str | None) -> Alias:
        """Parse ``type Name = <type>;`` with the cursor on ``type``."""
        self.next()  # 'type'
        name = self.next().value
        self.expect_punct("=")
        node = self.parse_type()
        if self.at_punct(";"):
            self.next()
        return Alias(
            name=name, type=node, annotations=parse_doc(doc), module=self.module
        )

    def parse_interface(self, doc: str | None) -> Interface:
        """Parse ``interface Name { ... }`` with the cursor on ``interface``."""
        self.next()  # 'interface'
        name = self.next().value
        fields = self.parse_object_body()
        return Interface(
            name=name,
            fields=list(fields),
            annotations=parse_doc(doc),
            module=self.module,
        )

    def parse_object_body(self) -> tuple[Field, ...]:
        """Parse ``{ field: Type; ... }`` including per-field doc comments."""
        self.expect_punct("{")
        fields: list[Field] = []
        pending_doc: str | None = None

        while not self.at_punct("}"):
            token = self.peek()
            if token.kind == "eof":
                raise ParseError(f"{self.module}: unterminated object type")
            if token.kind == "doc":
                self.next()
                pending_doc = token.value
                continue
            if token.kind == "punct" and token.value in ";,":
                self.next()
                continue

            name_token = self.next()
            if name_token.kind not in {"ident", "string"}:
                raise ParseError(
                    f"{self.module}:{name_token.line}: expected a field name, "
                    f"got {name_token.value!r}"
                )
            optional = False
            if self.at_punct("?"):
                self.next()
                optional = True
            self.expect_punct(":")
            node = self.parse_type()
            fields.append(
                Field(
                    name=name_token.value,
                    type=node,
                    annotations=parse_doc(pending_doc),
                    optional=optional,
                )
            )
            pending_doc = None
            if self.at_punct(";") or self.at_punct(","):
                self.next()

        self.expect_punct("}")
        return tuple(fields)

    def _skip_statement(self) -> None:
        """Skip a value-level statement, keeping bracket nesting balanced."""
        depth = 0
        while True:
            token = self.next()
            if token.kind == "eof":
                return
            if token.kind == "punct":
                if token.value in "{[(":
                    depth += 1
                elif token.value in "}])":
                    depth -= 1
                    if depth <= 0:
                        return
                elif token.value == ";" and depth == 0:
                    return

    # -- types ----------------------------------------------------------

    def parse_type(self) -> TypeNode:
        """Parse a type expression, allowing a leading ``|``."""
        if self.at_punct("|"):
            self.next()
        members = [self.parse_postfix()]
        while self.at_punct("|"):
            self.next()
            members.append(self.parse_postfix())
        if len(members) == 1:
            return members[0]
        return TUnion(tuple(members))

    def parse_postfix(self) -> TypeNode:
        """Parse a primary type followed by any number of ``[]`` suffixes."""
        node = self.parse_primary()
        while (
            self.at_punct("[")
            and self.peek(1).kind == "punct"
            and self.peek(1).value == "]"
        ):
            self.next()
            self.next()
            node = TArray(node)
        return node

    def parse_primary(self) -> TypeNode:
        """Parse a primary type."""
        if self.at_punct("("):
            self.next()
            node = self.parse_type()
            self.expect_punct(")")
            return node

        if self.at_punct("{"):
            return TObject(self.parse_object_body())

        if self.at_punct("["):
            self.next()
            items: list[TypeNode] = [self.parse_type()]
            while self.at_punct(","):
                self.next()
                items.append(self.parse_type())
            self.expect_punct("]")
            return TTuple(tuple(items))

        token = self.next()

        if token.kind == "string":
            return TLiteral(token.value)

        if token.kind == "number":
            text = token.value
            return TLiteral(int(text) if "." not in text else float(text))

        if token.kind == "ident":
            if token.value in {"number", "string", "boolean"}:
                return TPrimitive(token.value)
            if token.value == "null":
                return TNull()
            if token.value == "undefined":
                return TNull()
            if self.at_punct("[") and self.peek(1).kind == "string":
                # Indexed access: Foo["bar"]. A bare "[]" is an array suffix and
                # belongs to parse_postfix, not here.
                self.next()
                key = self.next()
                self.expect_punct("]")
                return TRef(f'{token.value}["{key.value}"]')
            return TRef(token.value)

        raise ParseError(
            f"{self.module}:{token.line}: unexpected token {token.value!r}"
        )


